/**
 * КЛЮЧИ ХРАНИЛИЩА. Все в одном месте, потому что это адреса данных, а не
 * названия переменных.
 *
 * ПЕРЕИМЕНОВЫВАТЬ НЕЛЬЗЯ. Ключ — адрес данных на устройстве, которое уже
 * работает: сменишь строку, и приложение начнёт читать пустоту, а прежние
 * данные останутся лежать под старым именем, недоступные и невидимые. Это не
 * рефакторинг, это потеря данных. Новое имя — только вместе с переносом
 * старого.
 *
 * Здесь нет имён коллекций Firestore: они перечислены в `COLLECTIONS`
 * (`data/db.ts`), под них же написаны правила доступа
 * (`firebase/firestore.rules`) — менять надо парой.
 *
 * Идея файла — из titovstroy/src/storageKeys.js, где та же ошибка стоила бы
 * боевых данных компании.
 */

/** База IndexedDB со всеми записями (по строке на запись). */
export const DB_NAME = 'personal-gym-os';
export const DB_VERSION = 1;

/** Весь снимок одной строкой — запасной путь, когда IndexedDB недоступна. */
export const LS_SNAPSHOT = 'personal-gym-os:snapshot';

/** Проба «а можно ли вообще писать»: приватное окно отвечает исключением. */
export const LS_PROBE = 'personal-gym-os:probe';

/** Настройки в key-value части хранилища (не localStorage). */
export const KV_SETTINGS = 'settings';

/**
 * «Подсказку про панель браузера уже закрыли». Только удобство: потеря ключа
 * возвращает подсказку, а не данные.
 */
export const LS_INSTALL_HINT_DISMISSED = 'gym-os:install-hint-dismissed';

/**
 * «Перенос данных с устройства в этот аккаунт уже решён» — по аккаунту, а не
 * общий: два аккаунта на одном телефоне не должны отвечать друг за друга.
 */
