import { describe, expect, it } from 'vitest';
import { swipeDirection, SWIPE_LIMITS } from './useSwipe';

/**
 * Жест — дополнительный способ листать упражнения, а не единственный (§51), и
 * ошибается он в худшую сторону: случайное листание посреди подхода уводит с
 * экрана, где человек собирался записать вес. Поэтому проверок несколько.
 */
const at = (x: number, y: number, t = 0) => ({ x, y, t });

describe('распознавание свайпа', () => {
  it('влево — следующее упражнение', () => {
    expect(swipeDirection(at(300, 400), at(180, 405, 200))).toBe('left');
  });

  it('вправо — предыдущее', () => {
    expect(swipeDirection(at(120, 400), at(240, 398, 200))).toBe('right');
  });

  it('короткий сдвиг не считается', () => {
    // Палец дрогнул на кнопке — листать нельзя.
    expect(swipeDirection(at(200, 400), at(200 - SWIPE_LIMITS.distance + 1, 400, 150))).toBeNull();
  });

  it('вертикальная прокрутка не считается', () => {
    expect(swipeDirection(at(200, 600), at(205, 200, 250))).toBeNull();
  });

  it('диагональ не считается', () => {
    // 100 по горизонтали при 60 по вертикали — это прокрутка списка подходов
    // пальцем наискось, а не листание.
    expect(swipeDirection(at(300, 400), at(200, 460, 250))).toBeNull();
  });

  it('ровно вдвое горизонтальнее — ещё не жест', () => {
    // Граница специально закрыта: «строго больше», иначе на пороге жест
    // срабатывал бы через раз и выглядел бы случайным.
    expect(swipeDirection(at(300, 400), at(200, 450, 250))).toBeNull();
  });

  it('медленное перетаскивание не считается', () => {
    // Палец лежал на экране секунду — человек не листал, а держал телефон.
    expect(swipeDirection(at(300, 400), at(150, 400, SWIPE_LIMITS.maxDurationMs + 1))).toBeNull();
  });

  it('движение без сдвига не считается', () => {
    expect(swipeDirection(at(200, 400), at(200, 400, 100))).toBeNull();
  });

  it('на пороге дистанции срабатывает', () => {
    expect(swipeDirection(at(300, 400), at(300 - SWIPE_LIMITS.distance, 400, 200))).toBe('left');
  });
});
