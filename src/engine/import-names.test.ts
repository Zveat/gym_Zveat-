describe('каждое название из выгрузки находит своё упражнение', () => {
  for (const [raw, name] of EXPECTED) {
    it(`${raw} → ${name}`, () => {
      const match = matchExercise(raw, exercises);
      expect(match.matchedName).toBe(name);
      // Ровно единица: всё ниже — догадка, а догадкам здесь не место.
      expect(match.score).toBe(1);
    });
  }

  it('все 26 названий попадают в разные нужные упражнения, а не в одно', () => {
    const ids = new Set(EXPECTED.map(([raw]) => matchExercise(raw, exercises).exerciseId));
    // 26 названий на 24 упражнения: два угла жима и два названия каната слиты.
    expect(ids.size).toBe(24);
    expect([...ids].every((id) => typeof id === 'string')).toBe(true);
  });
});

describe('scoreMatch не склеивает разные хваты', () => {
  it('«рукоятью» не считается за «рук»', () => {
    // Проверка длины стояла только на стороне запроса, поэтому длинный токен
    // цеплялся за трёхбуквенный токен кандидата и давал ровную единицу.
    const score = scoreMatch(
      'Разгибание рук на блоке с прямой рукоятью',
      'Разгибание рук на блоке с прямой канатом',
    );
    expect(score).toBeLessThan(1);
  });

  it('внутри одного кандидата точное совпадение забирает токен раньше префиксного', () => {
    // «прямой» есть в обоих, и если бы его забрал префикс «прямой рукоятью»,
    // счёт зависел бы от порядка токенов в названии.
    expect(
      scoreMatch('тяга нижнего блока к поясу', 'тяга нижнего блока к поясу'),
    ).toBe(1);
    expect(
      scoreMatch('тяга нижнего блока к поясу', 'тяга верхнего блока к поясу'),
    ).toBeLessThan(1);
  });

  it('один токен кандидата расходуется один раз', () => {
    // Иначе повтор слова в запросе набирал очки на одном слове кандидата.
    expect(scoreMatch('жим жим лежа', 'жим лежа')).toBeLessThan(1);
  });

  it('префикс всё ещё работает там, где для него и был: обрезанные слова', () => {
    expect(scoreMatch('жим гантел лежа', 'жим гантелей лежа')).toBe(1);
  });
});

describe('splitDayName', () => {
  it('делит настоящее название дня из выгрузки', () => {
    expect(splitDayName('День 1 - Грудь + Трицепс')).toEqual({
      name: 'День 1',
      title: 'Грудь + Трицепс',
    });
  });

  it('делит все пять дней владельца', () => {
    const days = [
      'День 1 - Грудь + Трицепс',
      'День 2 - Спина + Бицепс',
      'День 3 - Ноги + Плечи',
      'День 4 - Грудь + Спина',
      'День 5 - Плечи + Руки + Ноги',
    ].map(splitDayName);
    expect(days.map((d) => d.name)).toEqual(['День 1', 'День 2', 'День 3', 'День 4', 'День 5']);
    expect(days.every((d) => d.title.length > 0)).toBe(true);
  });

  it('понимает длинное тире и среднее, а не только дефис', () => {
    expect(splitDayName('День 2 — Спина').title).toBe('Спина');
    expect(splitDayName('День 2 – Спина').title).toBe('Спина');
  });

  it('не режет дефис внутри слова и плюс между группами', () => {
    expect(splitDayName('Грудь + Трицепс')).toEqual({ name: 'Грудь + Трицепс', title: '' });
    expect(splitDayName('Пресс-качалка')).toEqual({ name: 'Пресс-качалка', title: '' });
  });

  it('делит по первому тире: в названии групп тире больше нет', () => {
    expect(splitDayName('День 1 - Грудь - Трицепс')).toEqual({
      name: 'День 1',
      title: 'Грудь - Трицепс',
    });
  });
});
