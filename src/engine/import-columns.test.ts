import { describe, expect, it } from 'vitest';
import { matchExercise, parseWorkoutCsv } from './import-parser';
import { buildSeedExercises } from '@/domain/seed/exercise-library';

/**
 * Проверки на настоящей выгрузке из прежнего приложения: 24 тренировки, 516
 * подходов. Оба бага, которые здесь закрыты, теряли данные МОЛЧА — импорт
 * проходил без единого предупреждения, а недостача обнаруживалась потом в
 * истории.
 */
const LIBRARY = buildSeedExercises('2026-09-16T00:00:00Z');
const TODAY = new Date('2026-09-16T00:00:00Z');

// Заголовок и строки — как их отдаёт настоящий файл после распаковки .xlsx.
const REAL_CSV = [
  'Дата,Программа,Упражнение,Подход,"Вес, кг",Повторения',
  '07.08.2026,День 1 - Грудь + Трицепс,Жим штанги лежа,1.0,30.0,12.0',
  '07.08.2026,День 1 - Грудь + Трицепс,Жим штанги лежа,2.0,40.0,12.0',
  '07.08.2026,День 1 - Грудь + Трицепс,Сведение рук в тренажере,1.0,36.0,12.0',
].join('\n');

describe('колонки настоящей выгрузки', () => {
  const result = parseWorkoutCsv(REAL_CSV, LIBRARY, TODAY);

  it('«Вес, кг» распознаётся как вес', () => {
    // Сравнение заголовка целиком не совпадало ни с чем, колонка считалась
    // отсутствующей, и все 516 подходов записывались БЕЗ веса.
    const sets = result.workouts[0].exercises[0].sets;
    expect(sets.map((s) => s.weight)).toEqual([30, 40]);
  });

  it('«Программа» распознаётся как день тренировки', () => {
    expect(result.workouts[0].dayName).toBe('День 1 - Грудь + Трицепс');
  });

  it('дата в формате ДД.ММ.ГГГГ разбирается', () => {
    expect(result.workouts[0].date).toBe('2026-08-07');
  });

  it('разбор проходит без предупреждений', () => {
    expect(result.warnings).toEqual([]);
  });

  it('первое слово заголовка не даёт ложных совпадений', () => {
    // «повторения» не должно попасть в колонку по ключу «повт».
    const csv = 'дата,упражнение,повторения\n07.08.2026,Жим штанги лежа,12';
    expect(parseWorkoutCsv(csv, LIBRARY, TODAY).warnings).toEqual([]);
  });

  it('без колонки веса подходы всё равно пишутся, но без веса', () => {
    const csv = 'Дата,Упражнение,Повторения\n07.08.2026,Жим штанги лежа,12';
    const sets = parseWorkoutCsv(csv, LIBRARY, TODAY).workouts[0].exercises[0].sets;
    expect(sets[0].weight).toBeNull();
  });
});

describe('названия из прежнего приложения находят упражнения библиотеки', () => {
  /** Пары «как называлось у владельца» → «как называется здесь». */
  const PAIRS: [string, string][] = [
    ['Сведение рук в тренажере', 'Разводка в тренажере'],
    ['Тяга горизонтального блока с V-образной рукоятью', 'Тяга нижнего блока к поясу V-хватом'],
    ['Тяга горизонтального блока', 'Тяга нижнего блока к поясу'],
    ['Сгибание рук на бицепс в тренажере', 'ARM CURL (тренажер)'],
    ['Разгибание гантели из-за головы', 'Жим гантели из-за головы'],
    ['Разведения гантелей в стороны', 'Подъем гантелей в стороны'],
    ['Тяга нижнего блока одной рукой', 'Тяга одной рукой нижнего блока'],
    ['Жим гантелей под углом 30°', 'Жим гантелей под углом 30-40°'],
  ];

  it.each(PAIRS)('«%s» → «%s»', (raw, expected) => {
    expect(matchExercise(raw, LIBRARY).matchedName).toBe(expected);
  });

  it('горизонтальная тяга НЕ попадает в тягу верхнего блока', () => {
    // Раньше совпадало с «Тяга верхнего блока к груди» со счётом 0.50 — это
    // другое упражнение, и история двух движений слилась бы в одну.
    const m = matchExercise('Тяга горизонтального блока', LIBRARY);
    expect(m.matchedName).not.toMatch(/верхнего блока/);
    expect(m.score).toBe(1);
  });

  it('английский псевдоним продолжает работать', () => {
    expect(matchExercise('Barbell Bench Press', LIBRARY).matchedName).toBe('Жим штанги лежа');
  });
});
